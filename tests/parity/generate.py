#!/usr/bin/env python3
"""Generate the parity matrix: every macro against every trait shape.

The four macros are supposed to accept the same traits. They did not: seventeen of the
forty cells failed to compile, and which seventeen differed per macro, so a trait that
worked under `#[as_any]` could fail under `#[clone_box]` with an error pointing at the
caller's own source. Writing the matrix by hand is how that stays true, because a hand
written matrix is one somebody can leave a row out of.

Run from the repo root: python3 tests/parity/generate.py
"""
import pathlib

# A shape, and whether a macro that must form `dyn Trait` can accept it. Every shape here
# is ordinary Rust that a caller may reasonably write.
SHAPES = [
    ("plain_empty",    "pub trait {t} {{}}",                                              True),
    ("plain_methods",  "pub trait {t} {{ fn f(&self) -> u8; }}",                          True),
    ("generic",        "pub trait {t}<A> {{ fn f(&self) -> A; }}",                        True),
    ("generic_bound",  "pub trait {t}<A: Clone> {{ fn f(&self) -> A; }}",                 True),
    ("lifetime",       "pub trait {t}<'a> {{ fn f(&self) -> &'a u8; }}",                  True),
    ("supertrait",     "pub trait {t}: ::core::fmt::Debug {{ fn f(&self); }}",            True),
    ("where_clause",   "pub trait {t}<A> where A: Clone {{ fn f(&self) -> A; }}",         True),
    ("const_generic",  "pub trait {t}<const N: usize> {{ fn f(&self) -> [u8; N]; }}",     True),
    ("default_method", "pub trait {t} {{ fn f(&self) -> u8 {{ 1 }} }}",                   True),
    # `dyn T` is not a type while an associated type is unnamed, so the three macros that
    # must form one refuse it with a diagnostic of their own. `as_any` forms only `dyn Any`
    # and is unaffected, which is a difference in what the language permits rather than a
    # difference in the macros.
    ("assoc_type",     "pub trait {t} {{ type A; fn f(&self) -> Self::A; }}",             False),
]

MACROS = ["as_any", "as_super", "clone_box", "obj_eq"]
FORMS_DYN = {"as_super", "clone_box", "obj_eq"}

header = """//------------------------------------------------------------------------------
// Copyright (c) 2025 orgrinrt (orgrinrt@ikiuni.dev)
//                    Hiisi Digital Oy (contact@hiisi.digital)
// SPDX-License-Identifier: MPL-2.0
//------------------------------------------------------------------------------

//! GENERATED by tests/parity/generate.py. Do not edit; edit the generator.
//!
//! Every macro against every trait shape. A cell that compiles is a shape that macro
//! accepts, and the point of the file is that the column is the same for all four wherever
//! the language allows it to be.

#![allow(dead_code)]

"""

cells = []
count = 0
for mac in MACROS:
    cells.append(f"mod {mac}_shapes {{\n    use objkit::{mac};\n")
    for sname, tmpl, dyn_ok in SHAPES:
        if sname == "assoc_type" and mac in FORMS_DYN:
            continue  # refused, and asserted as a compile-fail case instead
        body = tmpl.format(t="".join(part.capitalize() for part in sname.split("_")))
        cells.append(f"    #[{mac}]\n    {body}\n")
        count += 1
    cells.append("}\n\n")

body = header + "".join(cells)
body += f"""/// The matrix is the assertion: this file compiling is {count} cells passing.
///
/// Counted here so that a generator producing an empty file fails rather than passing
/// silently, which is the way a generated suite usually dies.
#[test]
fn every_cell_in_the_matrix_compiled() {{
    assert_eq!(CELLS, {count}, "the generator wrote a different number of cells");
}}

const CELLS: usize = {count};
"""

out = pathlib.Path("tests/parity_matrix.rs")
out.write_text(body)
print(f"{count} cells over {len(MACROS)} macros and {len(SHAPES)} shapes -> {out}")
